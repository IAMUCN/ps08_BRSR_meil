export function buildManifestData(params: {
  bundleId: string;
  generatedAt: string;
  scope: ManifestScope;
  counts: ManifestCounts;
  files: ManifestFileEntry[];
}): BundleManifest {
  const { totalRecords, missingEvidenceCount } = params.counts;
  const completeness =
    totalRecords === 0
      ? 100
      : Math.max(0, Math.min(100, Math.round(((totalRecords - missingEvidenceCount) / totalRecords) * 100)));

  return {
    bundleId: params.bundleId,
    generatedAt: params.generatedAt,
    application: "TraceESG v1.0.0 (MEIL BRSR Reporting Platform)",
    scope: params.scope,
    counts: params.counts,
    traceabilityCompletenessPercent: completeness,
    files: params.files,
  };
}


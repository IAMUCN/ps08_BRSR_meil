import { createHash } from "node:crypto";

/**
 * Strips dangerous path traversal, control, and filesystem reserved characters.
 */
export function sanitizeFilename(name: string): string {
  const sanitized = name
    .replace(/^.*[/\\]/, "")
    .replace(/[/\\?%*:|"<>]/g, "_")
    .replace(/\.\.+/g, "_")
    .replace(/[\x00-\x1f\x80-\x9f]/g, "")
    .replace(/\s+/g, " ")
    .replace(/^_+|_+$/g, "")
    .trim();
  return sanitized || "document";
}

/**
 * Returns a safe, deterministic archive path for a supporting document.
 * Derived from the trusted document UUID with a sanitized extension.
 */
export function safeArchiveDocPath(documentId: string, originalFileName: string): string {
  const parts = originalFileName.split(".");
  const rawExt = parts.length > 1 ? parts[parts.length - 1] : "";
  const ext = sanitizeFilename(rawExt || "bin").replace(/[^a-zA-Z0-9]/g, "");
  return `evidence/documents/${documentId}.${ext || "bin"}`;
}

/**
 * Serializes headers and rows into RFC 4180 CSV format with CRLF line breaks.
 */
export function toCsv(
  headers: string[],
  rows: (string | number | boolean | null | undefined)[][],
): string {
  const escapeCell = (val: unknown): string => {
    if (val === null || val === undefined) return "";
    const str = String(val);
    if (str.includes(",") || str.includes('"') || str.includes("\n") || str.includes("\r")) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };
  const headerLine = headers.map(escapeCell).join(",");
  const dataLines = rows.map((r) => r.map(escapeCell).join(","));
  return [headerLine, ...dataLines].join("\r\n");
}

/**
 * Formats standard sha256sum compatible lines for a file manifest.
 */
export function formatChecksums(manifest: Array<{ path: string; sha256: string }>): string {
  const lines = manifest
    .filter((f) => f.path !== "checksums.sha256")
    .map((f) => `${f.sha256}  ${f.path}`);
  return lines.length > 0 ? lines.join("\r\n") + "\r\n" : "";
}

/**
 * Computes the cryptographic SHA-256 hex digest of given content.
 */
export function computeSha256(content: Buffer | Uint8Array | string): string {
  const buf = Buffer.isBuffer(content)
    ? content
    : typeof content === "string"
      ? Buffer.from(content, "utf8")
      : Buffer.from(content);
  return createHash("sha256").update(buf).digest("hex");
}

